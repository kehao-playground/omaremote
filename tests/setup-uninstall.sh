#!/usr/bin/env bash
# host/omaremote-setup's `uninstall` step against stubbed systemctl, sudo, voxtype, hyprctl, keyd and cargo, on a
# fixture tree per scenario. Never touches the real /etc/keyd, ~/.config, systemd, Voxtype or Hyprland.
# Usage: bash tests/setup-uninstall.sh [path to omaremote-setup]
set -uo pipefail
SRC=${1:-$(dirname "$0")/../host/omaremote-setup}
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
fail=0
check() { if [[ $2 == "$3" ]]; then printf '  ok    %-64s\n' "$1"; else printf '  FAIL  %-64s expected [%s] got [%s]\n' "$1" "$2" "$3"; fail=1; fi; }
has() { grep -qF -- "$2" <<<"$1" && echo yes || echo no; }
exists() { [[ -e $1 ]] && echo yes || echo no; }

LIB=$T/lib.sh
sed '/^main "\$@"$/d' "$SRC" > "$LIB"

ALSA_USER=$'# my own settings\npcm.!default { type pipewire }\n'
ATV_BLOCK=$'# BEGIN omaremote atvvoice (managed by omaremote-setup; do not edit)\npcm.atvvoice-xiaomi {\n  type pipewire\n  capture_node "atvvoice-xiaomi"\n  hint { show on description "ATVVoice remote (atvvoice-xiaomi)" }\n}\n# END omaremote atvvoice\n'
MIC_BLOCK=$'# BEGIN omaremote mic (managed by omaremote-setup; do not edit)\npcm.omaremote-mic {\n  type pipewire\n  capture_node "alsa_input.usb-cam"\n  hint { show on description "omaremote picked microphone" }\n}\n# END omaremote mic\n'
INPUT_BEFORE=$'-- user input settings\nhl.config({ input = { kb_layout = "us" } })\n'
# The shape ensure_xkb appends (keep in step with it).
XKB_GENERATED=$'\n-- Added by omaremote-setup. REQUIRED for the remote to work.\n-- keyd remaps the remote to F13-F24.\n-- To remove OmaRemote.s keyboard change entirely, delete this whole hl.config block.\nhl.config({\n  input = {\n    kb_options = "compose:caps,fkeys:basic_13-24",\n  },\n})\n'
# The hand-written block of the first installs, 2026-10-07.
XKB_HANDWRITTEN=$'\n-- Added by OmaRemote (omaremote-setup), 2026-10-07. REQUIRED for the remote to work.\n-- keyd remaps the remote to F13-F24.\n--\n-- To remove OmaRemote\'s keyboard change entirely, delete this whole hl.config block.\nhl.config({\n  input = {\n    kb_options = "compose:caps,shift:both_capslock_cancel,fkeys:basic_13-24",\n  },\n})\n'

# fresh: a full install in a new fixture directory B.
fresh() {
  B=$(mktemp -d "$T/case.XXXXXX")
  mkdir -p "$B/home" "$B/config/hypr" "$B/config/alsa" "$B/config/omaremote" "$B/config/systemd/user" "$B/etc" "$B/state/omaremote" "$B/home/.cargo/bin" "$B/lib"
  printf '%s%s%s' "$ALSA_USER" "$ATV_BLOCK" "$MIC_BLOCK" > "$B/config/alsa/asoundrc"
  printf '%s%s' "$INPUT_BEFORE" "$XKB_GENERATED" > "$B/config/hypr/input.lua"
  printf '%s\n%s\n' 'require("hypr.monitors")' 'require("hypr.omaremote")' > "$B/config/hypr/hyprland.lua"
  printf '%s\n' '-- Generated by omaremote-setup. Do not edit by hand; re-run "omaremote-setup binds".' 'hl.bind("F13", hl.dsp.global("omaremote:up"))' > "$B/config/hypr/omaremote.lua"
  echo '{"keys":{}}' > "$B/config/omaremote/config.json"
  printf '%s\n' '# Generated by omaremote-setup. Do not edit by hand; re-run `omaremote-setup atvvoice`.' '[Service]' > "$B/config/systemd/user/atvvoice.service"
  printf '%s\n' '[Unit]' 'Description=omaremote keytap (uinput hotkey taps for Typeless)' > "$B/config/systemd/user/omaremote-keytap.service"
  echo 'keytap' > "$B/lib/omaremote-keytap"
  echo 'rev=x patch=y' > "$B/state/omaremote/atvvoice.build"
  : > "$B/home/.cargo/bin/atvvoice"; chmod +x "$B/home/.cargo/bin/atvvoice"
  printf '# Generated by omaremote-setup for 2717:32b8. Do not edit by hand.\n[ids]\n' | tee "$B/etc/omaremote.conf" > "$B/etc/omaremote.conf.bak"
  echo omaremote-mic > "$B/voxdev"
}
snapshot() { (cd "$B" && find . -path ./calls.log -prune -o -path ./out.log -prune -o -type f -print0 | sort -z | xargs -0 md5sum); }

run() {   # run [uninstall args...]: the call log, its last line exit=N; stdin is the answers
  (
    export HOME=$B/home XDG_CONFIG_HOME=$B/config XDG_STATE_HOME=$B/state
    export OMAREMOTE_ALSA_RC=$B/config/alsa/asoundrc OMAREMOTE_ATV_UNIT=$B/config/systemd/user/atvvoice.service
    export OMAREMOTE_ATV_STAMP=$B/state/omaremote/atvvoice.build OMAREMOTE_ATV_BIN=${ATV_BIN_AT:-$B/home/.cargo/bin/atvvoice}
    export OMAREMOTE_KEYTAP_DIR=$B/lib OMAREMOTE_KEYTAP_UNIT=$B/config/systemd/user/omaremote-keytap.service
    # shellcheck disable=SC1090
    source "$LIB"
    KEYD_CONF=$B/etc/omaremote.conf
    [[ -n ${YES:-} ]] && ASSUME_YES=1
    set +e
    LOG=$B/calls.log; : > "$LOG"
    systemctl() { printf 'systemctl %s\n' "$*" >> "$LOG"; [[ " $* " == *" is-active "* ]] && { [[ -n ${ACTIVE:-} ]]; return; }; return 0; }
    sudo() { printf 'sudo %s\n' "$*" >> "$LOG"; "$@"; }
    keyd() { printf 'keyd %s\n' "$*" >> "$LOG"; }
    hyprctl() { printf 'hyprctl %s\n' "$*" >> "$LOG"; [[ $1 == configerrors ]] && printf '%s' "${HYPR_ERRORS:-}"; return 0; }
    cargo() { printf 'cargo %s\n' "$*" >> "$LOG"; [[ $1 == uninstall ]] && rm -f "$OMAREMOTE_ATV_BIN"; return 0; }
    voxtype() {
      printf 'voxtype %s\n' "$*" >> "$LOG"
      case "$*" in
        "config get audio.device --json") jq -n --arg v "$(cat "$B/voxdev" 2>/dev/null)" '{key:"audio.device", file_value:(if $v == "" then null else $v end)}' ;;
        "config unset audio.device") rm -f "$B/voxdev" ;;
      esac
    }
    ( set -e; cmd_uninstall "$@" ) > "$B/out.log" 2>&1   # set -e, as the script runs: an early exit must show
    echo "exit=$?" >> "$LOG"
  )
  cat "$B/calls.log"
}
out() { cat "$B/out.log"; }

# 1. --yes on a full install removes every item, and keeps everything that is not OmaRemote's
fresh; o=$(YES=1 ACTIVE=1 run)
check "full --yes: exit 0"                                  "yes" "$(has "$o" "exit=0")"
check "voxtype audio.device unset"                         "yes" "$(has "$o" "voxtype config unset audio.device")"
check "asoundrc keeps the user's lines byte for byte"      "${ALSA_USER}x" "$(cat "$B/config/alsa/asoundrc"; printf x)"
check "...with one copy of the old file"                   "$(printf '%s%s%sx' "$ALSA_USER" "$ATV_BLOCK" "$MIC_BLOCK")" "$(cat "$B/config/alsa/asoundrc.omaremote.bak"; printf x)"
check "...and the ALSA lock file gone"                     "no"  "$(exists "$B/config/alsa/asoundrc.omaremote.lock")"
check "voxtype restarted once to drop the PCM"             "1"   "$(grep -c 'try-restart voxtype' <<<"$o")"
check "atvvoice disabled and stopped"                      "yes" "$(has "$o" "systemctl --user disable --now atvvoice")"
check "keytap disabled and stopped"                        "yes" "$(has "$o" "systemctl --user disable --now omaremote-keytap")"
check "atvvoice unit deleted"                              "no"  "$(exists "$B/config/systemd/user/atvvoice.service")"
check "keytap unit deleted"                                "no"  "$(exists "$B/config/systemd/user/omaremote-keytap.service")"
check "keytap script and its directory deleted"            "no"  "$(exists "$B/lib")"
check "ATVVoice uninstalled through cargo"                 "yes" "$(has "$o" "cargo uninstall -q atvvoice")"
check "...binary gone"                                     "no"  "$(exists "$B/home/.cargo/bin/atvvoice")"
check "build stamp gone"                                   "no"  "$(exists "$B/state/omaremote/atvvoice.build")"
check "hyprland.lua keeps its other lines"                 'require("hypr.monitors")' "$(cat "$B/config/hypr/hyprland.lua")"
check "omaremote.lua deleted"                              "no"  "$(exists "$B/config/hypr/omaremote.lua")"
check "input.lua back to its pre-setup content"            "${INPUT_BEFORE}x" "$(cat "$B/config/hypr/input.lua"; printf x)"
check "Hyprland reloaded"                                  "yes" "$(has "$o" "hyprctl reload")"
check "keyd conf and its .bak deleted through sudo"        "yes" "$(has "$o" "sudo rm -f -- $B/etc/omaremote.conf $B/etc/omaremote.conf.bak")"
check "...both gone"                                       "no"  "$(exists "$B/etc/omaremote.conf")$(exists "$B/etc/omaremote.conf.bak" | sed 's/no//')"
check "keyd reloaded (it was active)"                      "yes" "$(has "$o" "sudo keyd reload")"
check "settings kept without --purge"                      "yes" "$(exists "$B/config/omaremote/config.json")"
check "the plugin remove command is printed last"          "    omarchy plugin remove io.github.kehao-chen.omaremote" "$(out | tail -1)"
check "nothing listed as left in place"                    "no"  "$(has "$(out)" "Left in place")"

# 2. --dry-run changes nothing at all and runs nothing that writes
fresh; before=$(snapshot); o=$(YES=1 ACTIVE=1 run --dry-run)
check "dry run: exit 0"                                    "yes" "$(has "$o" "exit=0")"
check "dry run: every file unchanged"                      "$before" "$(snapshot)"
check "dry run: no sudo"                                   "no"  "$(has "$o" "sudo")"
check "dry run: no unit disabled"                          "no"  "$(has "$o" "disable")"
check "dry run: no voxtype write"                          "no"  "$(has "$o" "unset")"
check "dry run: no reload"                                 "no"  "$(has "$o" "reload")"
check "dry run: still names every item"                    "yes" "$(has "$(out)" "omaremote.conf.bak (needs sudo")"

# 3. answering no to every question changes nothing and says what was kept
fresh; before=$(snapshot); o=$(yes n | ACTIVE=1 run)
check "all no: exit 0"                                     "yes" "$(has "$o" "exit=0")"
check "all no: every file unchanged"                       "$before" "$(snapshot)"
check "all no: no sudo"                                    "no"  "$(has "$o" "sudo")"
check "all no: lists what was kept"                        "yes" "$(has "$(out)" "kept at your request: $B/etc/omaremote.conf")"

# 4. answers are per item: yes to the first only
fresh; o=$(printf 'y\nn\nn\nn\nn\nn\nn\nn\n' | run)
check "first yes: voxtype unset"                           "yes" "$(has "$o" "voxtype config unset audio.device")"
check "first yes: asoundrc untouched"                      "$(printf '%s%s%sx' "$ALSA_USER" "$ATV_BLOCK" "$MIC_BLOCK")" "$(cat "$B/config/alsa/asoundrc"; printf x)"

# 5. what setup did not write is left alone
fresh
echo hw:1 > "$B/voxdev"
printf '%s\n' '[Service]' 'ExecStart=/usr/bin/atvvoice' > "$B/config/systemd/user/atvvoice.service"
printf '%s\n' '-- my own omaremote binds' > "$B/config/hypr/omaremote.lua"
printf '%s%s%s' "$ALSA_USER" "$ATV_BLOCK" "${MIC_BLOCK%$'# END omaremote mic\n'}" > "$B/config/alsa/asoundrc"   # mic block lost its END
o=$(YES=1 run)
check "foreign: voxtype value kept"                        "no"  "$(has "$o" "unset")"
check "foreign: hand-written atvvoice unit kept"           "yes" "$(exists "$B/config/systemd/user/atvvoice.service")"
check "foreign: ...and not disabled"                       "no"  "$(has "$o" "disable --now atvvoice")"
check "foreign: hand-written omaremote.lua kept"           "-- my own omaremote binds" "$(cat "$B/config/hypr/omaremote.lua")"
check "foreign: the require line still goes"               "0"  "$(grep -c omaremote "$B/config/hypr/hyprland.lua")"
check "broken mic markers: the good atvvoice block goes"   "0"  "$(grep -c 'BEGIN omaremote atvvoice' "$B/config/alsa/asoundrc")"
check "broken mic markers: the broken block stays"         "1"   "$(grep -c 'BEGIN omaremote mic' "$B/config/alsa/asoundrc")"
check "foreign items are listed at the end"                "yes" "$(has "$(out)" "was not written by omaremote-setup; left alone")"
check "...the broken block too"                            "yes" "$(has "$(out)" "has broken markers; delete it by hand")"

# 6. the first installs' hand-written kb_options block is recognised
fresh; printf '%s%s' "$INPUT_BEFORE" "$XKB_HANDWRITTEN" > "$B/config/hypr/input.lua"; o=$(YES=1 run)
check "hand-written block: removed"                        "${INPUT_BEFORE}x" "$(cat "$B/config/hypr/input.lua"; printf x)"

# 7. a marker whose block has another shape is left for the user
fresh; odd=$INPUT_BEFORE${XKB_GENERATED/fkeys:basic_13-24/ctrl:nocaps}; printf '%s' "$odd" > "$B/config/hypr/input.lua"; o=$(YES=1 run)
check "odd block: input.lua unchanged"                     "${odd}x" "$(cat "$B/config/hypr/input.lua"; printf x)"
check "odd block: listed"                                  "yes" "$(has "$(out)" "kb_options block in an unexpected shape")"

# 8. --purge deletes the settings and state directories
fresh; o=$(YES=1 run --purge)
check "purge: settings gone"                               "no"  "$(exists "$B/config/omaremote")"
check "purge: state gone"                                  "no"  "$(exists "$B/state/omaremote")"

# 9. nothing installed: every item says so, nothing runs
B=$(mktemp -d "$T/case.XXXXXX"); mkdir -p "$B/home" "$B/config/hypr"; : > "$B/config/hypr/hyprland.lua"; : > "$B/config/hypr/input.lua"
o=$(YES=1 run)
check "empty: exit 0"                                      "yes" "$(has "$o" "exit=0")"
check "empty: no sudo, no systemctl writes, no reload"     "no"  "$(grep -Ec 'sudo|disable|daemon-reload|hyprctl reload|unset' <<<"$o" | sed 's/^0$/no/')"
check "empty: no asoundrc created"                         "no"  "$(exists "$B/config/alsa/asoundrc")"

# 10. a binary outside ~/.cargo is removed directly, never through cargo
fresh; mkdir -p "$B/elsewhere"; : > "$B/elsewhere/atvvoice"; chmod +x "$B/elsewhere/atvvoice"
o=$(YES=1 ATV_BIN_AT=$B/elsewhere/atvvoice run)
check "other path: not through cargo"                      "no"  "$(has "$o" "cargo uninstall")"
check "other path: removed"                                "no"  "$(exists "$B/elsewhere/atvvoice")"

# 11. a Hyprland config error after the reload is reported, not hidden
fresh; o=$(YES=1 HYPR_ERRORS="input.lua:3: syntax error" run)
check "config error: listed"                               "yes" "$(has "$(out)" "Hyprland reports config errors after the reload")"

# 12. an unknown option is refused before anything is touched
fresh; before=$(snapshot); o=$(YES=1 run --force)
check "unknown option: exit 1"                             "yes" "$(has "$o" "exit=1")"
check "unknown option: nothing changed"                    "$before" "$(snapshot)"

# 13. review fixes
# a symlinked (dotfile-managed) hyprland.lua: the link stays, and the backup is a real copy of the old content
fresh; mv "$B/config/hypr/hyprland.lua" "$B/dotfile.lua"; ln -s "$B/dotfile.lua" "$B/config/hypr/hyprland.lua"
old=$(cat "$B/dotfile.lua"); o=$(YES=1 run)
check "symlink: still a symlink"                           "yes" "$([[ -L $B/config/hypr/hyprland.lua ]] && echo yes || echo no)"
check "symlink: target rewritten"                          'require("hypr.monitors")' "$(cat "$B/dotfile.lua")"
check "symlink: backup is a file with the old content"     "file:$old" "$([[ -L $B/config/hypr/hyprland.lua.omaremote.bak ]] && echo link || echo file):$(cat "$B/config/hypr/hyprland.lua.omaremote.bak")"

# a require that is not setup's exact line: omaremote.lua must stay, or Hyprland's config breaks
fresh; printf '%s\n' 'require("hypr.monitors")' '  require("hypr.omaremote") -- remote' > "$B/config/hypr/hyprland.lua"; o=$(YES=1 run)
check "variant require: omaremote.lua kept"                "yes" "$(exists "$B/config/hypr/omaremote.lua")"
check "variant require: hyprland.lua unchanged"            '  require("hypr.omaremote") -- remote' "$(tail -1 "$B/config/hypr/hyprland.lua")"
check "variant require: listed"                            "yes" "$(has "$(out)" "loads omaremote.lua from a line that is not setup's own")"

# an atvvoice binary without setup's build stamp is not setup's
fresh; rm -f "$B/state/omaremote/atvvoice.build"; o=$(YES=1 run)
check "no stamp: binary kept"                              "yes" "$(exists "$B/home/.cargo/bin/atvvoice")"
check "no stamp: never offered to cargo"                   "no"  "$(has "$o" "cargo uninstall")"
check "no stamp: listed"                                   "yes" "$(has "$(out)" "has no omaremote-setup build stamp")"

# answering no to the binary keeps its stamp
fresh; o=$(printf 'n\nn\nn\nn\nn\nn\nn\nn\n' | run)
check "binary kept: stamp kept"                            "yes" "$(exists "$B/state/omaremote/atvvoice.build")"

# a keyd config without setup's header is not deleted
fresh; printf '[ids]\n*\n' > "$B/etc/omaremote.conf"; o=$(YES=1 run)
check "foreign keyd conf: kept"                            "yes" "$(exists "$B/etc/omaremote.conf")"
check "foreign keyd conf: generated .bak still deleted"    "no"  "$(exists "$B/etc/omaremote.conf.bak")"

# the ALSA lock stays when the blocks stay
fresh; : > "$B/config/alsa/asoundrc.omaremote.lock"; o=$(printf 'n\nn\nn\nn\nn\nn\nn\nn\n' | run)
check "blocks kept: lock file kept"                        "yes" "$(exists "$B/config/alsa/asoundrc.omaremote.lock")"

# Voxtype kept but its PCM removed: the user is told
fresh; o=$(printf 'n\ny\nn\nn\nn\nn\nn\nn\n' | run)
check "voxtype kept, PCM gone: warned"                     "yes" "$(has "$(out)" "still names omaremote-mic, which no longer exists")"

# input.lua whose last line has no newline keeps it that way
fresh; printf '%s%s%s' "$INPUT_BEFORE" "$XKB_GENERATED" '-- tail without newline' > "$B/config/hypr/input.lua"; o=$(YES=1 run)
check "no final newline: kept"                             "${INPUT_BEFORE}-- tail without newlinex" "$(cat "$B/config/hypr/input.lua"; printf x)"

# the whole run survives set -e: every item, then the summary
fresh; o=$(YES=1 ACTIVE=1 run --purge)
check "set -e: reaches the final hint"                     "    omarchy plugin remove io.github.kehao-chen.omaremote" "$(out | tail -1)"

exit $fail
